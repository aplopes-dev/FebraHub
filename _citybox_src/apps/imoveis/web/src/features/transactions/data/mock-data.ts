export function cloneTransaction(tx: Transaction): Transaction {
  return {
    ...tx,
    split: {
      ...tx.split,
      others: [...tx.split.others],
    },
    rental: tx.rental
      ? {
          ...tx.rental,
          deductions: [...tx.rental.deductions],
        }
      : undefined,
    activityLog: [...tx.activityLog],
  };
}

export function cloneTransactionsSeed(): Transaction[] {
  return TRANSACTIONS_SEED.map(cloneTransaction);
}
