function activity(
  id: string,
  at: string,
  actorName: string,
  message: string,
): Transaction['activityLog'][number] {
  return { id, at, actorName, message };
}

function saleSplit(
  grossCents: number,
  commissionPercent: number,
  agency: number,
  captor: number,
  seller: number,
) {
  return buildCommissionSplit(grossCents, commissionPercent, {
    agencyPercent: agency,
    captorPercent: captor,
    sellerPercent: seller,
  });
}

